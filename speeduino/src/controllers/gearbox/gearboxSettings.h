#pragma once

/**
 * @file gearboxSettings.h
 * @brief The gearbox settings as TunerStudio sees them (page 17), and their conversion to the
 *        structures the shift controller works with.
 *
 * ================================================================================================
 *  BACKGROUND FOR READERS WITHOUT PREVIOUS KNOWLEDGE
 * ================================================================================================
 *
 *  TunerStudio (the tuning program on the laptop) edits settings in numbered "pages". Each page is a
 *  block of bytes in the ECU. The .ini file (reference/speeduino.ini) describes which byte of the
 *  page means what. Page 17 of this fork holds the settings of the paddle shift gearbox: switch it
 *  on, which pins the paddles are on, how long the engine is cut, how long the actuator moves, ...
 *
 *  gearboxSettingsPage_t is exactly this block of 64 bytes. Its BYTE LAYOUT is shared with the .ini
 *  file (generated by tools/gen_can_table_ini.py), so it must not be changed on its own; the
 *  static_asserts below stop the build if the layout drifts.
 *
 *  The page is stored in the EEPROM (see storage.cpp). An EEPROM that never had the page written
 *  reads as "all zero" here, which means: gearbox DISABLED.
 *
 *  gearboxApplySettings() converts the raw page into the gearbox_config_t of the sequencer
 *  (clamping silly values) and the pin numbers. It is plain logic and tested on a PC.
 */

#include <stddef.h>
#include <stdint.h>
#include "gearboxController.h"

/** The 64-byte settings page. Byte offsets are noted per field and are used by the .ini file. */
struct gearboxSettingsPage_t
{
  // ---- byte 0: switches ----
  uint8_t enabled            : 1; ///< 0: Gearbox switched on (needs both paddle pins).
  uint8_t allowDownToNeutral : 1; ///< 1: A downshift from 1st gear moves to neutral.
  uint8_t cutOnUpshift       : 1; ///< 2: Cut the engine during upshifts.
  uint8_t cutOnDownshift     : 1; ///< 3: Cut the engine during downshifts.
  uint8_t cutIgnition        : 1; ///< 4: The cut switches the ignition off.
  uint8_t cutFuel            : 1; ///< 5: The cut switches the fuel off.
  uint8_t useFeedback        : 1; ///< 6: Wait for the position feedback instead of fixed times (feedback is not wired up yet).
  uint8_t unused0            : 1; ///< 7
  // ---- byte 1: electrical ----
  uint8_t paddlesActiveLow   : 1; ///< 0: Paddle switches connect the pin to ground (internal pull-up used).
  uint8_t neutralActiveLow   : 1; ///< 1: Neutral switch connects the pin to ground in neutral.
  uint8_t unused1            : 6; ///< 2...7
  // ---- bytes 2...5 ----
  uint8_t maxGear;                ///< 2: Highest gear of the box (1...6).
  uint8_t pinPaddleUp;            ///< 3: Pin of the upshift paddle (255 = not connected).
  uint8_t pinPaddleDown;          ///< 4: Pin of the downshift paddle (255 = not connected).
  uint8_t pinNeutral;             ///< 5: Pin of the neutral switch (255 = not fitted).
  // ---- bytes 6...35: numbers (little endian) ----
  uint16_t cutMinRpm;             ///< 6:  No cut below this engine speed.
  uint16_t maxCutMs;              ///< 8:  Hard limit of the cut duration in ms (0 = never cut).
  uint16_t downshiftMaxRpm;       ///< 10: Refuse a downshift if the predicted rpm is above this (0 = no check).
  uint16_t upTravel;              ///< 12: Actuator travel for an upshift, permille (0...1000).
  uint16_t downTravel;            ///< 14: Actuator travel for a downshift, permille (0...1000).
  uint16_t positionTolerance;     ///< 16: Accepted position error with feedback, permille.
  uint16_t debounceMs;            ///< 18: Paddle debounce time.
  uint16_t cutLeadMs;             ///< 20: The cut starts this long before the actuator moves.
  uint16_t moveMs;                ///< 22: Time allowed for the move.
  uint16_t holdMs;                ///< 24: Time the actuator stays at the target.
  uint16_t returnMs;              ///< 26: Time allowed for the return to centre.
  uint16_t verifyMs;              ///< 28: Time to wait for the gear sensor to report the new gear (0 = no check).
  uint16_t minIntervalMs;         ///< 30: Minimum time between the starts of two shifts.
  uint16_t maxShiftMs;            ///< 32: Watchdog for the whole sequence.
  uint16_t faultLockoutMs;        ///< 34: Pause after a fault before paddles are accepted again.
  // ---- rest ----
  uint8_t reserved[28];           ///< 36...63: unused
} __attribute__((packed));

// The .ini file addresses these fields by byte offset (tools/gen_can_table_ini.py). Do not change without changing it.
static_assert(sizeof(gearboxSettingsPage_t) == 64U, "gearbox settings page must be 64 bytes");
static_assert(offsetof(gearboxSettingsPage_t, maxGear) == 2U, "ini: maxGear at byte 2");
static_assert(offsetof(gearboxSettingsPage_t, pinPaddleUp) == 3U, "ini: pinPaddleUp at byte 3");
static_assert(offsetof(gearboxSettingsPage_t, pinNeutral) == 5U, "ini: pinNeutral at byte 5");
static_assert(offsetof(gearboxSettingsPage_t, cutMinRpm) == 6U, "ini: cutMinRpm at byte 6");
static_assert(offsetof(gearboxSettingsPage_t, positionTolerance) == 16U, "ini: positionTolerance at byte 16");
static_assert(offsetof(gearboxSettingsPage_t, moveMs) == 22U, "ini: moveMs at byte 22");
static_assert(offsetof(gearboxSettingsPage_t, faultLockoutMs) == 34U, "ini: faultLockoutMs at byte 34");
static_assert(offsetof(gearboxSettingsPage_t, reserved) == 36U, "ini: reserved starts at byte 36");

/** Marker byte stored in the EEPROM next to the page, so a never-written EEPROM area is not mistaken for settings. */
constexpr uint8_t GEARBOX_SETTINGS_EEPROM_MARKER = 0xA7U;

/**
 * @brief Converts the raw settings page into the controller's configuration.
 *
 * Values are clamped to sane ranges (maxGear 1...6, travels and tolerance 0...1000). The pins are
 * copied as they are; whether a pin is usable is decided by gearboxInit(). The controller's
 * actuator pointer and state are not touched.
 */
void gearboxApplySettings(const gearboxSettingsPage_t& page, gearboxController_t& ctrl);

/**
 * @brief Re-reads the settings page into the controller, but only when something changed and no shift is in progress.
 *
 * If a pin number changed, the pins are set up again through @p hal. Call this regularly (every
 * loop is fine; it compares 64 bytes).
 * @param cached  a copy of the page as it was last applied (kept by the caller, starts all zero)
 * @return true if the new settings were applied in this call
 */
bool gearboxRefreshSettings(const gearboxSettingsPage_t& page, gearboxSettingsPage_t& cached, bool& cachedValid,
                            gearboxController_t& ctrl, const gearboxHal_t& hal);
